fun main () {
    // ------------------------------------------
    // 4. KATEGORI: TIPE DATA BOOLEAN
    // ------------------------------------------
    println("=== 4. TIPE DATA BOOLEAN ===")

    var benar: Boolean = true
    var salah: Boolean = false

