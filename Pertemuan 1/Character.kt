fun main () {
    // ------------------------------------------
    // 3. KATEGORI: TIPE DATA CHARACTER
    // ------------------------------------------
    println("=== 3. TIPE DATA CHARACTER ===")

    // Menggunakan inisial nama 'A', 'D', 'S' (Angga Dwi Saputro)
    // var atau variabel untuk mendeklarasikan nilai yang bisa diubah 
    // kemudian char tipe data khusus karakter tunggal dan tipe data ini wajih diapit dengan petik satu 
    // huruf ADS merupakan nilai karakter dalam tugas ini 
    var char1: Char = 'A'
    var char2: Char = 'D'
    var char3: Char = 'S'
    // println perintah untuk mengeksekusi atau untuk mencetak 
    println("Char 1: $char1")
    println("Char 2: $char2")
    println("Char 3: $char3")
    println()
}